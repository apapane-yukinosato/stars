/* 長期歳差モデル（数万年スケールで有効）
 * Vondrák, Capitaine, Wallace (2011) "New precession expressions, valid for long time intervals",
 * A&A 534, A22 （正誤表 A&A 541, C1 (2012) を反映）。係数は論文の表より。
 * J2000.0 の赤道座標 → 指定した年の平均赤道座標 への回転行列と、その年の天の北極の方向を返す。
 */
(function () {
  'use strict';
  const AS2RAD = Math.PI / 648000;
  const EPS0 = 84381.406 * AS2RAD; // J2000.0 の黄道傾斜角

  // [1/周期(世紀), psi_A:cos, omega_A:cos, chi_A:cos, psi_A:sin, omega_A:sin, chi_A:sin]
  const PREC = [
    [1 / 402.90, -22206.325946, 1267.727824, -13765.92405, -3243.236469, -8571.476251, -2206.967126],
    [1 / 256.75, 12236.649447, 1702.324248, 13511.858383, -3969.723769, 5309.796459, -4186.752711],
    [1 / 292.00, -1589.008343, -2970.553839, -1455.229106, 7099.207893, -610.393953, 6737.949677],
    [1 / 537.22, 2482.103195, 693.790312, 1054.394467, -1903.696711, 923.201931, -856.922846],
    [1 / 241.45, 150.32292, -14.724451, 0, 146.435014, 3.759055, 0],
    [1 / 375.22, -13.632066, -516.649401, -112.300144, 1300.630106, -40.691114, 957.149088],
    [1 / 157.87, 389.43742, -356.794454, 202.769908, 1727.498039, 80.437484, 1709.440735],
    [1 / 274.20, 2031.433792, -129.552058, 1936.050095, 299.854055, 807.300668, 154.425505],
    [1 / 203.00, 363.748303, 256.129314, 0, -1217.125982, 83.712326, 0],
    [1 / 440.00, -896.747562, 190.266114, -655.484214, -471.367487, -368.654854, -243.520976],
    [1 / 170.72, -926.9957, 95.103991, -891.898637, -441.682145, -191.881064, -406.539008],
    [1 / 713.37, 37.070667, -332.907067, 0, -86.169171, -4.26377, 0],
    [1 / 313.00, -597.682468, 131.337633, 0, -308.320429, -270.353691, 0],
    [1 / 128.38, 66.282812, 82.731919, -333.322021, -422.815629, 11.602861, -446.656435],
    [1 / 202.00, 0, 0, 327.517465, 0, 0, -1049.071786],
    [1 / 315.00, 0, 0, -494.780332, 0, 0, -301.504189],
    [1 / 136.32, 0, 0, 585.492621, 0, 0, 41.34874],
    [1 / 490.00, 0, 0, 110.512834, 0, 0, 142.525186],
  ];

  function angles(year) {
    const T = (year - 2000) / 100; // J2000.0 からのユリウス世紀
    const w = 2 * Math.PI * T;
    let psi = 0, omega = 0, chi = 0;
    for (const r of PREC) {
      const c = Math.cos(w * r[0]), s = Math.sin(w * r[0]);
      psi += r[1] * c + r[4] * s;
      omega += r[2] * c + r[5] * s;
      chi += r[3] * c + r[6] * s;
    }
    psi += ((289e-9 * T - 0.00740913) * T + 5042.7980307) * T + 8473.343527;
    omega += ((151e-9 * T + 0.00000146) * T - 0.4436568) * T + 84283.175915;
    chi += ((-61e-9 * T + 0.00001472) * T + 0.0790159) * T - 19.65727;
    return { psi: psi * AS2RAD, omega: omega * AS2RAD, chi: chi * AS2RAD };
  }

  const R1 = (a) => { const c = Math.cos(a), s = Math.sin(a); return [1, 0, 0, 0, c, s, 0, -s, c]; };
  const R3 = (a) => { const c = Math.cos(a), s = Math.sin(a); return [c, s, 0, -s, c, 0, 0, 0, 1]; };
  function mul(a, b) {
    const o = new Array(9);
    for (let i = 0; i < 3; i++) for (let j = 0; j < 3; j++) o[i * 3 + j] = a[i * 3] * b[j] + a[i * 3 + 1] * b[3 + j] + a[i * 3 + 2] * b[6 + j];
    return o;
  }

  /** J2000.0 赤道座標 → 指定年の平均赤道座標 の行列（行優先） */
  function matrix(year) {
    const a = angles(year);
    return mul(R3(a.chi), mul(R1(-a.omega), mul(R3(-a.psi), R1(EPS0))));
  }

  /** 指定年の天の北極の方向（J2000.0 赤道座標系の単位ベクトル） */
  function poleVec(year) {
    const m = matrix(year);
    return [m[6], m[7], m[8]];
  }

  window.Precession = { angles, matrix, poleVec };
})();
